BEGIN;
CREATE EXTENSION IF NOT EXISTS pg_trgm;
SET LOCAL search_path TO public, extensions;

CREATE TABLE categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CONSTRAINT ck_categories_name
        CHECK (name = btrim(name) AND name ~ '[^[:space:]]'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_categories_name_lower ON categories (lower(name));
INSERT INTO categories (name) VALUES
    ('Electronics'), ('Workspace'), ('Home & living'), ('Accessories'), ('Stationery');

CREATE TABLE products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL CONSTRAINT ck_products_name CHECK (length(btrim(name)) > 0),
    description TEXT CONSTRAINT ck_products_description CHECK (description IS NULL OR length(description) <= 5000),
    price NUMERIC(12,2) NOT NULL CONSTRAINT ck_products_price CHECK (price >= 0 AND price <> 'NaN'::numeric),
    quantity INTEGER NOT NULL CONSTRAINT ck_products_quantity CHECK (quantity >= 0),
    category_id INTEGER CONSTRAINT fk_products_category_id_categories
        REFERENCES categories(id) ON DELETE RESTRICT,
    image_url VARCHAR(2048) CONSTRAINT ck_products_image_url CHECK (image_url IS NULL OR image_url ~ '^https://[^[:space:]]+$'),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_products_category_id ON products (category_id);
CREATE INDEX ix_products_name_trgm ON products USING gin (name gin_trgm_ops) WHERE is_deleted IS FALSE;
CREATE INDEX ix_products_created_id ON products (created_at DESC, id DESC) WHERE is_deleted IS FALSE;
COMMIT;
